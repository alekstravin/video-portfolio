function renderProductionNote(container, id) {
  const note = productionNotes[id];
  if (!note) {
    container.replaceChildren();
    return;
  }

  const block = document.createElement('div');
  block.className = 'production-note';
  const technology = document.createElement('dl');
  const label = document.createElement('dt');
  label.textContent = 'Технологии';
  const description = document.createElement('dd');
  description.textContent = note.technology;
  technology.append(label, description);

  const details = document.createElement('details');
  const summary = document.createElement('summary');
  summary.textContent = 'Возможный промт';
  const example = document.createElement('p');
  example.textContent = note.prompt;
  details.append(summary, example);
  block.append(technology, details);
  container.replaceChildren(block);
}

for (const container of document.querySelectorAll('[data-production]')) {
  renderProductionNote(container, container.dataset.production);
}
